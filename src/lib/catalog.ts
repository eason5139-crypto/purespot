function batches(protein: number, moisture: number) {
  return batchDates.map((date, i) => ({
    date,
    batch: `PS-${date.replaceAll("-", "")}`,
    protein: protein + [0.4, 0.8, 0.5, 1.1, 0.7, 0.9][i]!,
    moisture: moisture + [0.2, 0.1, 0.4, 0.2, 0.3, 0.1][i]!,
    ash: 6.1 + (i % 3) * 0.1,
  }));
}
